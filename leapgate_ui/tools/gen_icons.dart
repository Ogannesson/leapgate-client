// Converts the <symbol> icons of the mockup base file (docs/新界面/样稿/A-基础.html
// in the leapgate repository) into Flutter Path code: app/lib/icons/lg_icons.g.dart.
// See docs/新界面/03-实施方案.md §4.2.
//
// Usage, from leapgate_ui/:
//   dart run tools/gen_icons.dart <path to A-基础.html> [output file]
//
// Only dart:io is used, so no pub get is needed for this script.

