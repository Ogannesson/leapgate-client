void main(List<String> args) {
  if (args.isEmpty || args.length > 2) {
    stderr.writeln('usage: dart run tools/gen_icons.dart <A-基础.html> [output]');
    exit(64);
  }
  final out = args.length == 2
      ? args[1]
      : File.fromUri(
          Platform.script.resolve('../app/lib/icons/lg_icons.g.dart'),
        ).path;
  File(out).writeAsStringSync(generate(File(args[0]).readAsStringSync()));
  stdout.writeln('wrote $out');
}

/// Returns the content of lg_icons.g.dart for the given A-基础.html source.
String generate(String html) {
  final symbols = RegExp(
    r'<symbol id="([^"]+)" viewBox="([^"]+)"[^>]*>(.*?)</symbol>',
    dotAll: true,
  ).allMatches(html).where((m) => !_skip.contains(m.group(1))).toList();
  final seen = <String>{};
  final names = <String>[];
  final cases = StringBuffer();
  for (final m in symbols) {
    final id = m.group(1)!;
    if (!seen.add(id)) throw FormatException('duplicate symbol $id');
    final name = _dartName(id);
    names.add(name);
    final vb = m
        .group(2)!
        .trim()
        .split(RegExp(r'[\s,]+'))
        .map(double.parse)
        .toList();
    if (vb[0] != 0 || vb[1] != 0)
      throw FormatException('$id: viewBox must start at 0 0');
    final parts = _parseBody(id, m.group(3)!);
    cases.writeln(
      '    LgIcons.$name => LgIconData(${_n(vb[2])}, ${_n(vb[3])}, [',
    );
    for (final p in parts) {
      cases.writeln('        $p,');
    }
    cases.writeln('      ]),');
  }
  final b = StringBuffer()
    ..writeln('// GENERATED by tools/gen_icons.dart from docs/新界面/样稿/A-基础.html')
    ..writeln(
      '// (leapgate repository). Do not edit by hand. Regenerate from leapgate_ui/:',
    )
    ..writeln('//   dart run tools/gen_icons.dart <path to A-基础.html>')
    ..writeln()
    ..writeln("part of 'lg_icon.dart';")
    ..writeln()
    // Keeps the file byte-identical to the generator output
    // (test/gallery_and_icons_test.dart compares them).
    ..writeln('// dart format off')
    ..writeln()
    ..writeln(
      '/// Icons of the mockups. Prefixes: none for `i-*`, mark (`m-*`, compact',
    )
    ..writeln(
      '/// connection markers), route (`p-*`, detail markers), window (`w-*`),',
    )
    ..writeln('/// statusBar (`sb-*`).')
    ..writeln('enum LgIcons {');
  for (final n in names) {
    b.writeln('  $n,');
  }
  b
    ..writeln('}')
    ..writeln()
    ..writeln('LgIconData _buildIcon(LgIcons icon) => switch (icon) {')
    ..write(cases)
    ..writeln('    };');
  return b.toString();
}

/// Ids whose plain mapping would be a Dart keyword.
const _renames = {'i-external': 'externalLink'};

String _dartName(String id) {
  if (_renames.containsKey(id)) return _renames[id]!;
  final dash = id.indexOf('-');
  final prefix = id.substring(0, dash);
  if (!_prefixes.containsKey(prefix))
    throw FormatException('unknown prefix in $id');
  final words = [
    if (_prefixes[prefix]!.isNotEmpty) _prefixes[prefix]!,
    ...id.substring(dash + 1).split('-'),
  ];
  final name =
      words.first +
      words.skip(1).map((w) => w[0].toUpperCase() + w.substring(1)).join();
  if (_reserved.contains(name) ||
      !RegExp(r'^[a-z][A-Za-z0-9]*$').hasMatch(name)) {
    throw FormatException('$id maps to an unusable Dart name "$name"');
  }
  return name;
}

/// Presentation state inherited down the element tree.
class _Style {
  _Style({
    required this.fill,
    required this.stroke,
    required this.width,
    required this.scaled,
    required this.cap,
    required this.join,
    this.dash,
    this.transform,
  });

  bool fill;
  bool stroke;
  double width;

  /// False only for the `.ic` default stroke, which stays 2 logical px at any size.
  bool scaled;
  String cap;
  String join;
  List<double>? dash;
  List<double>? transform;

  _Style copy() => _Style(
    fill: fill,
    stroke: stroke,
    width: width,
    scaled: scaled,
    cap: cap,
    join: join,
    dash: dash,
    transform: transform,
  );

  void apply(String id, Map<String, String> a) {
    final fillAttr = a['fill'];
    if (fillAttr != null) fill = _paint(id, fillAttr);
    final strokeAttr = a['stroke'];
    if (strokeAttr != null) stroke = _paint(id, strokeAttr);
    final w = a['stroke-width'];
    if (w != null) {
      width = double.parse(w);
      scaled = true;
    }
    cap = a['stroke-linecap'] ?? cap;
    join = a['stroke-linejoin'] ?? join;
    final d = a['stroke-dasharray'];
    if (d != null) {
      dash = d == 'none'
          ? null
          : d.trim().split(RegExp(r'[\s,]+')).map(double.parse).toList();
    }
    final t = a['transform'];
    if (t != null) {
      if (transform != null) {
        throw FormatException('$id: nested transforms are not supported');
      }
      transform = _rotation(id, t);
    }
  }
}

const _paintAttributes = {
  'fill',
  'stroke',
  'stroke-width',
  'stroke-linecap',
  'stroke-linejoin',
  'stroke-dasharray',
};

/// Attributes each element may carry; anything else would be silently
/// ignored, so it is an error instead.
const _allowedAttributes = {
  'g': {..._paintAttributes, 'transform'},
  'path': {..._paintAttributes, 'd'},
  'circle': {..._paintAttributes, 'cx', 'cy', 'r'},
  'rect': {..._paintAttributes, 'x', 'y', 'width', 'height', 'rx', 'ry'},
};

bool _paint(String id, String v) {
  if (v == 'none') return false;
  if (v == 'currentColor') return true;
  throw FormatException(
    '$id: only none and currentColor are supported, got $v',
  );
}

/// Only `rotate(a cx cy)` occurs in the icons; returned as [a, cx, cy].
List<double> _rotation(String id, String t) {
  final m = RegExp(
    r'^rotate\(\s*([-\d.]+)[\s,]+([-\d.]+)[\s,]+([-\d.]+)\s*\)$',
  ).firstMatch(t.trim());
  if (m == null) throw FormatException('$id: unsupported transform $t');
  return [for (var i = 1; i <= 3; i++) double.parse(m.group(i)!)];
}

List<String> _parseBody(String id, String body) {
  // The `.ic` class (A-基础.html:102) gives i-* icons stroke-only drawing with a
  // round 2 px line; the other symbols set everything on their elements.
  final root = id.startsWith('i-')
      ? _Style(
          fill: false,
          stroke: true,
          width: 2,
          scaled: false,
          cap: 'round',
          join: 'round',
        )
      : _Style(
          fill: true,
          stroke: false,
          width: 1,
          scaled: true,
          cap: 'butt',
          join: 'miter',
        );
  final stack = [root];
  final parts = <String>[];
  for (final m in RegExp(r'<(/?)(\w+)([^>]*?)(/?)>').allMatches(body)) {
    final closing = m.group(1)!.isNotEmpty;
    final tag = m.group(2)!;
    final attrs = {
      for (final a in RegExp(r'([\w-]+)="([^"]*)"').allMatches(m.group(3)!))
        a.group(1)!: a.group(2)!,
    };
    final allowed = _allowedAttributes[tag];
    if (allowed == null)
      throw FormatException('$id: unsupported element <$tag>');
    final unknown = attrs.keys.where((k) => !allowed.contains(k));
    if (unknown.isNotEmpty) {
      throw FormatException(
        '$id: unsupported attributes on <$tag>: ${unknown.join(', ')}',
      );
    }
    if (tag == 'g') {
      if (closing) {
        stack.removeLast();
      } else {
        stack.add(stack.last.copy()..apply(id, attrs));
      }
      continue;
    }
    if (closing) continue;
    final s = stack.last.copy()..apply(id, attrs);
    final String path;
    switch (tag) {
      case 'path':
        path = _pathData(id, attrs['d']!);
      case 'circle':
        path =
            'Path()..addOval(Rect.fromCircle(center: const Offset(${_n(_a(attrs, 'cx'))}, ${_n(_a(attrs, 'cy'))}), '
            'radius: ${_n(_a(attrs, 'r'))}))';
      case 'rect':
        final rect =
            'const Rect.fromLTWH(${_n(_a(attrs, 'x'))}, ${_n(_a(attrs, 'y'))}, '
            '${_n(_a(attrs, 'width'))}, ${_n(_a(attrs, 'height'))})';
        final rx = attrs['rx'] ?? attrs['ry'];
        path = rx == null
            ? 'Path()..addRect($rect)'
            : 'Path()..addRRect(RRect.fromRectAndRadius($rect, const Radius.circular(${_n(double.parse(rx))})))';
      default:
        throw FormatException('$id: unsupported element <$tag>');
    }
    if (!s.fill && !s.stroke) continue;
    final rotated = s.transform == null
        ? path
        : '($path).transform(_rotation(${s.transform!.map(_n).join(', ')}))';
    final args = <String>[rotated];
    if (s.fill) args.add('fill: true');
    if (s.stroke) {
      args.add('stroke: ${_n(s.width)}');
      if (!s.scaled) args.add('scaleStroke: false');
      if (s.cap != 'butt') args.add('cap: StrokeCap.${s.cap}');
      if (s.join != 'miter') args.add('join: StrokeJoin.${s.join}');
      if (s.dash != null) args.add('dash: [${s.dash!.map(_n).join(', ')}]');
    }
    parts.add('LgIconPart(${args.join(', ')})');
  }
  return parts;
}

double _a(Map<String, String> attrs, String k) => double.parse(attrs[k] ?? '0');

/// Number literal without float noise: at most 4 decimals, no trailing zeros.
String _n(double v) {
  var s = (v.abs() < 5e-5 ? 0.0 : v).toStringAsFixed(4);
  s = s.replaceFirst(RegExp(r'\.?0+$'), '');
  return s == '-0' ? '0' : s;
}

/// Translates SVG path data into absolute Flutter Path calls.
String _pathData(String id, String d) {
  final t = _PathTokens(id, d);
  final calls = <String>[];
  var x = 0.0, y = 0.0, sx = 0.0, sy = 0.0;
  double? cx2, cy2; // last cubic control point, for S
  double? qx, qy; // last quadratic control point, for T
  String? cmd;
  while (t.more) {
    if (t.atCommand) cmd = t.command();
    if (cmd == null)
      throw FormatException('$id: path data must start with a command');
    final rel = cmd == cmd.toLowerCase();
    final c = cmd.toUpperCase();
    double ax(double v) => rel ? x + v : v;
    double ay(double v) => rel ? y + v : v;
    var keepC = false, keepQ = false;
    switch (c) {
      case 'M':
        x = ax(t.number());
        y = ay(t.number());
        sx = x;
        sy = y;
        calls.add('moveTo(${_n(x)}, ${_n(y)})');
        cmd = rel ? 'l' : 'L'; // further pairs are lineto
      case 'L':
        x = ax(t.number());
        y = ay(t.number());
        calls.add('lineTo(${_n(x)}, ${_n(y)})');
      case 'H':
        x = ax(t.number());
        calls.add('lineTo(${_n(x)}, ${_n(y)})');
      case 'V':
        y = rel ? y + t.number() : t.number();
        calls.add('lineTo(${_n(x)}, ${_n(y)})');
      case 'C' || 'S':
        final double x1, y1;
        if (c == 'C') {
          x1 = ax(t.number());
          y1 = ay(t.number());
        } else {
          x1 = cx2 == null ? x : 2 * x - cx2;
          y1 = cy2 == null ? y : 2 * y - cy2;
        }
        final x2 = ax(t.number()), y2 = ay(t.number());
        final ex = ax(t.number()), ey = ay(t.number());
        calls.add(
          'cubicTo(${_n(x1)}, ${_n(y1)}, ${_n(x2)}, ${_n(y2)}, ${_n(ex)}, ${_n(ey)})',
        );
        cx2 = x2;
        cy2 = y2;
        keepC = true;
        x = ex;
        y = ey;
      case 'Q' || 'T':
        final double x1, y1;
        if (c == 'Q') {
          x1 = ax(t.number());
          y1 = ay(t.number());
        } else {
          x1 = qx == null ? x : 2 * x - qx;
          y1 = qy == null ? y : 2 * y - qy;
        }
        final ex = ax(t.number()), ey = ay(t.number());
        calls.add(
          'quadraticBezierTo(${_n(x1)}, ${_n(y1)}, ${_n(ex)}, ${_n(ey)})',
        );
        qx = x1;
        qy = y1;
        keepQ = true;
        x = ex;
        y = ey;
      case 'A':
        final rx = t.number().abs(), ry = t.number().abs(), rot = t.number();
        final large = t.flag(), sweep = t.flag();
        final ex = ax(t.number()), ey = ay(t.number());
        if (rx == 0 || ry == 0) {
          calls.add('lineTo(${_n(ex)}, ${_n(ey)})');
        } else {
          final radius = rx == ry
              ? 'Radius.circular(${_n(rx)})'
              : 'Radius.elliptical(${_n(rx)}, ${_n(ry)})';
          final opts = [
            'radius: const $radius',
            if (rot != 0) 'rotation: ${_n(rot)}',
            if (large) 'largeArc: true',
            if (sweep) 'clockwise: true' else 'clockwise: false',
          ];
          calls.add(
            'arcToPoint(const Offset(${_n(ex)}, ${_n(ey)}), ${opts.join(', ')})',
          );
        }
        x = ex;
        y = ey;
      case 'Z':
        calls.add('close()');
        x = sx;
        y = sy;
        cmd = null; // a number after Z is an error; a new command must follow
      default:
        throw FormatException('$id: unsupported path command $cmd');
    }
    if (!keepC) cx2 = cy2 = null;
    if (!keepQ) qx = qy = null;
  }
  return 'Path()${calls.map((c) => '..$c').join()}';
}

class _PathTokens {
  _PathTokens(this.id, this.s);

  final String id;
  final String s;
  int i = 0;

  void _skipSeparators() {
    while (i < s.length && ' \t\r\n,'.contains(s[i])) {
      i++;
    }
  }

  bool get more {
    _skipSeparators();
    return i < s.length;
  }

  bool get atCommand {
    _skipSeparators();
    return i < s.length && RegExp(r'[A-Za-z]').hasMatch(s[i]);
  }

  String command() {
    _skipSeparators();
    return s[i++];
  }

  double number() {
    _skipSeparators();
    final m = RegExp(
      r'[-+]?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?',
    ).matchAsPrefix(s, i);
    if (m == null) throw FormatException('$id: number expected at $i in "$s"');
    i = m.end;
    return double.parse(m.group(0)!);
  }

  /// Arc flags are single characters and may be written without separators.
  bool flag() {
    _skipSeparators();
    final c = s[i++];
    if (c != '0' && c != '1')
      throw FormatException('$id: arc flag expected at ${i - 1} in "$s"');
    return c == '1';
  }
}
